"""Generate src/data/weekly-quiz-cards.ts from study note 07 (weekly review questions).

Run from interactive-lessons/web:  python3 scripts/weekly_quiz_cards.py
Weeks 1-7 become recall cards ({q, a, code?}); week 8 becomes the 20-question mixed check.
"""
import json
import re
from pathlib import Path

NOTE = Path(__file__).resolve().parents[3] / "docs/study-notes/07 - Bộ câu hỏi ôn tập hằng tuần.md"
OUT = Path(__file__).resolve().parents[1] / "src/data/weekly-quiz-cards.ts"


def plain(text: str) -> str:
    """Drop Obsidian bold markers and turn [[Note|alias]] / [[Note#x]] links into readable text."""
    text = text.replace("**", "")
    text = re.sub(r"\[\[([^\]|]*)\|([^\]]*)\]\]", r"\2", text)
    return re.sub(r"\[\[([^\]#]*)(#[^\]]*)?\]\]", r"bài “\1”", text)


def main() -> None:
    weeks, final = [], []
    for part in re.split(r"^## ", NOTE.read_text(), flags=re.M)[1:]:
        title, body = part.split("\n", 1)
        if title.startswith("Tuần 8"):
            final = [plain(re.sub(r"^\d+\. ", "", line).strip()) for line in body.splitlines() if re.match(r"^\d+\. ", line)]
            continue
        cards = []
        for m in re.finditer(r"^\*\*(\d+)\.\*\* (.*?)(?=^\*\*\d+\.\*\* |^---|\Z)", body, flags=re.M | re.S):
            question, _, answer = m.group(2).partition("> [!success]- Đáp án")
            code = re.findall(r"```\w*\n(.*?)```", question, flags=re.S)
            q = re.sub(r"\s*\n\s*", " ", re.sub(r"```\w*\n.*?```", "", question, flags=re.S).strip())
            a = "\n".join(re.sub(r"^> ?", "", line) for line in answer.strip().splitlines() if line.startswith(">")).strip()
            card = {"q": plain(q), "a": plain(a)}
            if code:
                card["code"] = "\n".join(c.rstrip() for c in code)
            cards.append(card)
        weeks.append({"title": title.strip(), "cards": cards})
    OUT.write_text(
        "// Generated by scripts/weekly_quiz_cards.py from study note 07; edit the note and rerun, not this file.\n"
        "export type RecallCard = { q: string; a: string; code?: string };\n"
        f"export const weeklyCards: {{ title: string; cards: RecallCard[] }}[] = {json.dumps(weeks, ensure_ascii=False, indent=1)};\n"
        f"export const finalMock: string[] = {json.dumps(final, ensure_ascii=False, indent=1)};\n"
    )
    print(f"{sum(len(w['cards']) for w in weeks)} cards in {len(weeks)} weeks, {len(final)} final questions -> {OUT.name}")


if __name__ == "__main__":
    main()
