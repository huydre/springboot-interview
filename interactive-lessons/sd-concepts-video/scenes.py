def threads(prefix, x0, y, tone, n=8, style=""):
    """A row of small squares standing for a thread pool; the red (busy) row is laid on top of the free one."""
    return "".join(el(f"{prefix}{i}", x0 + i * 56, y, 44, 44, "", f"gbox {tone} r", style, " data-layout-allow-overlap")
                   for i in range(n))


def tip(id_, x, y, dx, dy, tone):
    """A 22 px arrow ending at (x, y), pointing along (dx, dy): the head for the end of a polyline trace."""
    return arrow(id_, [(x - dx * 22, y - dy * 22), (x, y)], tone)


def GO(id_, d=0.0, dur=0.5):
    """Draw an arrow line, then pop its head (no travelling light)."""
    return [DRAW(f"#{id_}-p", d, dur), IN(f"#{id_}-h", "pop", d + dur - 0.05, 0.25)]


